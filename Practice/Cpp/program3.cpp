// Jay Ganesh
#include<bits/stdc++.h>
#include<iostream>

using namespace std;

int main()
{
    for(int i = 0; i<=5;i++)
    {
        cout<<"Jay Ganesh.."<<endl;
    }

    // While Lopp
    int i = 0;
    while(i<=5)
    {
        cout<<"Jay Ganesh"<<endl;
        i++;
    }

    // do while
int j = 0;
    do
    {
        cout<<"Jay Ganesh.."<<endl;
        j++;
    } while (j<=5);
    
    return 0;
}